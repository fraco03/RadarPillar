"""Check local imports, model registries and build inputs without CUDA installed.

Run from any directory: python tools/check_project_structure.py
This does not replace an inference/training smoke test on the NVIDIA target.
"""
import ast
import importlib.util
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def check_structure():
    errors = []
    trees = {}
    for folder in ('pcdet', 'tools'):
        for path in (ROOT / folder).rglob('*.py'):
            trees[path] = ast.parse(path.read_text(), filename=str(path))
    setup_tree = ast.parse((ROOT / 'setup.py').read_text())
    extensions = {}
    for node in ast.walk(setup_tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
            continue
        if node.func.id != 'make_cuda_ext':
            continue
        args = {k.arg: ast.literal_eval(k.value) for k in node.keywords}
        extensions[args['module'] + '.' + args['name']] = args
        for source in args['sources']:
            path = ROOT.joinpath(*args['module'].split('.'), source)
            if not path.is_file():
                errors.append(f'Missing CUDA build source: {path.relative_to(ROOT)}')

    def exists(module):
        path = ROOT.joinpath(*module.split('.'))
        return path.is_dir() or path.with_suffix('.py').is_file() or module in extensions

    def symbols(module):
        path = ROOT.joinpath(*module.split('.'))
        path = path / '__init__.py' if path.is_dir() else path.with_suffix('.py')
        tree = trees.get(path)
        if tree is None:
            return set()
        names = set()
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
                names.add(node.name)
            elif isinstance(node, (ast.Import, ast.ImportFrom)):
                names.update(a.asname or a.name.split('.')[0] for a in node.names)
            elif isinstance(node, ast.Assign):
                names.update(n.id for target in node.targets for n in ast.walk(target)
                             if isinstance(n, ast.Name))
        return names

    for path, tree in trees.items():
        rel = path.relative_to(ROOT)
        package = '.'.join(rel.parent.parts)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name.startswith('pcdet.') and not exists(alias.name):
                        errors.append(f'{rel}:{node.lineno}: missing {alias.name}')
            elif isinstance(node, ast.ImportFrom):
                module = node.module or ''
                if node.level:
                    module = importlib.util.resolve_name('.' * node.level + module, package)
                if not module.startswith(('pcdet', 'tools')):
                    # Entry points add tools/ to sys.path.
                    if module.split('.')[0] in ('eval_utils', 'train_utils', 'visual_utils'):
                        module = 'tools.' + module
                    else:
                        continue
                if module == 'pcdet.version':
                    continue  # Generated by setup.py.
                if not exists(module):
                    errors.append(f'{rel}:{node.lineno}: missing {module}')
                    continue
                available = symbols(module)
                for alias in node.names:
                    if alias.name != '*' and alias.name not in available and not exists(module + '.' + alias.name):
                        errors.append(f'{rel}:{node.lineno}: missing {module}.{alias.name}')

    registries = {
        'MODEL': 'pcdet.models.detectors',
        'VFE': 'pcdet.models.backbones_3d.vfe',
        'BACKBONE_3D': 'pcdet.models.backbones_3d',
        'MAP_TO_BEV': 'pcdet.models.backbones_2d.map_to_bev',
        'BACKBONE_2D': 'pcdet.models.backbones_2d',
        'DENSE_HEAD': 'pcdet.models.dense_heads',
    }
    config_count = 0
    for path in (ROOT / 'tools/cfgs').rglob('*.yaml'):
        config_count += 1
        section = None
        for line in path.read_text().splitlines():
            base = re.match(r'\s*_BASE_CONFIG_:\s*[\x27\x22]?([^\s\x27\x22]+)', line)
            if base and not (ROOT / base[1]).is_file():
                errors.append(f'{path.relative_to(ROOT)}: missing base config {base[1]}')
            match = re.match(r'^(\s*)(\w+):\s*$', line)
            if match and match[2] in registries:
                section = match[2]
            name = re.match(r'\s+NAME:\s*(\w+)\s*$', line)
            if name and section:
                module = registries[section]
                registry_tree = trees[ROOT.joinpath(*module.split('.'), '__init__.py')]
                registry = next(n.value for n in registry_tree.body
                                if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__all__' for t in n.targets))
                keys = {ast.literal_eval(k) for k in registry.keys}
                if name[1] not in keys:
                    errors.append(f'{path.relative_to(ROOT)}: {name[1]} absent from {module}')
                section = None
            dataset = re.match(r'DATASET:\s*[\x27\x22]?(\w+)', line)
            if dataset and dataset[1] not in symbols('pcdet.datasets'):
                errors.append(f'{path.relative_to(ROOT)}: missing dataset {dataset[1]}')
    if errors:
        raise SystemExit('\n'.join(errors))
    print(f'PASS: {len(trees)} Python files parsed; local imports and symbols resolved; '
          f'{config_count} configs checked; {len(extensions)} CUDA extension source lists checked.')


if __name__ == '__main__':
    check_structure()
